    private void btnregistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnregistrarActionPerformed
        if (cmbtipo.getSelectedIndex() == 0 || txtnombrecl.getText().isEmpty() ||
            txthorariocl.getText().isEmpty() || txtcupocl.getText().isEmpty() ||
            txtpreciocl.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Complete todos los campos");
            return;
        }
        try {
            int cupo = Integer.parseInt(txtcupocl.getText());
            float precio = Float.parseFloat(txtpreciocl.getText());
            if (cupo <= 0) { JOptionPane.showMessageDialog(null, "El cupo debe ser mayor a cero."); return; }
            if (precio <= 0) { JOptionPane.showMessageDialog(null, "El precio debe ser mayor a cero."); return; }
            Resultado resultado = claseService.registrarClase(
                cmbtipo.getSelectedItem().toString(),
                idSucursal,
                idEmpleadoSeleccionado == 0 ? null : idEmpleadoSeleccionado,
                txtnombrecl.getText(),
                txthorariocl.getText(),
                cupo, precio);
            JOptionPane.showMessageDialog(null, resultado.mensaje());
            if (resultado.exito()) { limpiar(); cargartabla(); }
        } catch (Exception e) { JOptionPane.showMessageDialog(null, e.toString()); }
    }//GEN-LAST:event_btnregistrarActionPerformed

