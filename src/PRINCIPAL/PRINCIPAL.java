    private void btnAvisoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAvisoActionPerformed
        JTextArea txtAviso = new JTextArea(8, 32);
        txtAviso.setLineWrap(true);
        txtAviso.setWrapStyleWord(true);
        try {
            avisoService.obtenerUltimo().ifPresent(a -> txtAviso.setText(a.mensaje()));
        } catch (Exception e) {
            // Si falla la carga del aviso actual, se abre el cuadro vacío igual.
        }
        int opcion = JOptionPane.showConfirmDialog(this, new JScrollPane(txtAviso),
                "Publicar anuncio para los clientes", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
        if (opcion != JOptionPane.OK_OPTION) return;

        String mensaje = txtAviso.getText().trim();
        if (mensaje.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El anuncio no puede estar vacío.");
            return;
        }
        Resultado resultado = avisoService.publicar(idEmpleado, mensaje);
        JOptionPane.showMessageDialog(this, resultado.mensaje());
    }//GEN-LAST:event_btnAvisoActionPerformed

